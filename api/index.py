from http.server import BaseHTTPRequestHandler
import json
from urllib.parse import urlparse, parse_qs
import sys

# Import the main core functionality directly from the library module
try:
    from streamgrabber.cli import main as run_streamgrabber
except ImportError:
    # Fallback option if package structure differs across updates
    from streamgrabber import main as run_streamgrabber

class handler(BaseHTTPRequestHandler):
    def do_GET(self):
        parsed_url = urlparse(self.path)
        query_params = parse_qs(parsed_url.query)
        imdb_id = query_params.get('imdb_id', [None])[0]
        
        headers = {
            'Content-Type': 'application/json',
            'Access-Control-Allow-Origin': '*',
            'Access-Control-Allow-Methods': 'GET',
            'Access-Control-Allow-Headers': 'Content-Type'
        }

        if parsed_url.path != '/api' and parsed_url.path != '/api/index':
            self.send_response(404)
            for k, v in headers.items(): self.send_header(k, v)
            self.end_headers()
            self.wfile.write(json.dumps({"error": "Path not found. Use /api?imdb_id=ID"}).encode())
            return

        if not imdb_id:
            self.send_response(400)
            for k, v in headers.items(): self.send_header(k, v)
            self.end_headers()
            self.wfile.write(json.dumps({"error": "Missing imdb_id parameter"}).encode())
            return

        try:
            # Safely capture the printed output generated by the function in memory
            from io import StringIO
            old_stdout = sys.stdout
            sys.stdout = mystdout = StringIO()
            
            # Execute the function internally inside Python instead of terminal command lines
            # This passes the ID argument and the required listing flags directly
            try:
                run_streamgrabber([imdb_id, "--list"])
            finally:
                sys.stdout = old_stdout
            
            stream_url = mystdout.getvalue().strip()
            
            self.send_response(200)
            for k, v in headers.items(): self.send_header(k, v)
            self.end_headers()
            self.wfile.write(json.dumps({"imdb_id": imdb_id, "m3u8_url": stream_url}).encode())
            
        except Exception as e:
            self.send_response(500)
            for k, v in headers.items(): self.send_header(k, v)
            self.end_headers()
            self.wfile.write(json.dumps({"error": str(e)}).encode())
